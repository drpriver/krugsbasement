import os
from typing import List, Tuple, Union, Optional, Set
INPUT = 'message-enum.txt'
Comment = str
TypeName = str
class EnumInfo:
    def __init__(self, name:str, type:str):
        assert type in {'str', 'int'}
        self.name = name
        self.type = type
        self.items: List[Union[Comment, Tuple[str, str, Optional[Comment]]]] = []
        self.values:Set[str] = set()
        self.keys:Set[str] = set()
    def add_line(self, line:str) -> None:
        k, v = line.split('=')
        self.append(k, v)
    def add_comment(self, comment:Comment) -> None:
        self.items.append(comment.strip())
    def append(self, k:str, v:str) -> None:
        k = k.strip()
        v = v.strip()
        comment = None
        if '#' in v:
            v, comment = v.split('#')
            v = v.strip()
            comment = comment.strip()
        if k in self.keys:
            raise Exception(self.name, 'duplicate key:', k)
        if v in self.values:
            raise Exception(self.name, 'duplicate value:', v)
        self.keys.add(k)
        self.values.add(v)
        self.items.append((k, v, comment))

class StructInfo:
    def __init__(self, name:str) -> None:
        self.name = name
        self.members: List[Union[Comment, Tuple[str, TypeName, Optional[Comment]]]] = []
        self.member_names: Set[str] = set()
    def add_line(self, line:str) -> None:
        k, v = line.split('=')
        self.append(k, v)
    def add_comment(self, comment:Comment) -> None:
        self.members.append(comment.strip())
    def append(self, name:str, type:str) -> None:
        name = name.strip()
        type = type.strip()
        comment = None
        if '#' in type:
            a, b = type.split('#')
            type = a.strip()
            comment = b.strip()
        if name in self.member_names:
            raise Exception()
        self.member_names.add(name)
        self.members.append((name, type, comment))

class UnionInfo:
    def __init__(self, name:str) -> None:
        self.name = name
        self.variants: List[Union[Comment, Tuple[TypeName, Optional[Comment]]]] = []
        self.variant_types: Set[str] = set()
    def add_comment(self, comment:Comment) -> None:
        self.variants.append(comment.strip())
    def add_line(self, line:str) -> None:
        self.append(line)
    def append(self, type:str) -> None:
        type = type.strip()
        comment = None
        if '#' in type:
            a, b = type.split('#')
            type = a.strip()
            comment = b.strip()
        if type in self.variant_types:
            raise Exception()
        self.variant_types.add(type)
        self.variants.append((type, comment))

Info = Union[EnumInfo, StructInfo, UnionInfo]

def get_values() -> List[Info]:
    fp = open(INPUT, encoding='utf-8')
    result = []
    current_info: Info
    for line in fp:
        line = line.rstrip()
        if not line:
            continue
        if line[0] == '\t':
            raise Exception('tab')
        if line.strip()[0] == '#':
            current_info.add_comment(line.strip()[1:])
            continue
        if line[0] != ' ':
            if line.startswith('struct'):
                line = line[len('struct'):].strip()
                current_info = StructInfo(line)
            elif line.startswith('enum'):
                line = line[len('enum'):].strip()
                name, type = line.split(':')
                current_info = EnumInfo(name.strip(), type.strip())
            elif line.startswith('union'):
                line = line[len('union'):].strip()
                current_info = UnionInfo(line)
            else:
                raise Exception
            result.append(current_info)
            continue
        current_info.add_line(line)
    fp.close()
    return result

def make_python(infos: List[Info]) -> None:
    fp = open('WebDnD/messages.py', 'w', encoding='utf-8')
    def p(*args, **kwargs):
        print(*args, **kwargs, file=fp)
    p('# Generated via', os.path.relpath(__file__))
    p(f'# Input at "{INPUT}"')
    p('# DO NOT EDIT THIS FILE DIRECTLY')
    p('from enum import Enum')
    p('from typing import Tuple, Union, List, Literal')
    p('')
    def convert_type(t:str) -> str:
        if t.startswith('['):
            inner = t[1:-1]
            inner = convert_type(inner.strip())
            return f'List[{inner}]'
        if '.' in t: # hack
            return f'Literal[{t}]'
        if t not in {'str', 'int', 'float'}:
            return f"'{t}'"
        return t
    for info in infos:
        if isinstance(info, EnumInfo):
            p(f'class {info.name}({info.type}, Enum):')
            for item in info.items:
                if isinstance(item, str):
                    p(f'    # {item}')
                    continue
                elif info.type == 'str':
                    if item[2]:
                        p(f"    {item[0]} = '{item[1]}' # {item[2]}")
                    else:
                        p(f"    {item[0]} = '{item[1]}'")
                else:
                    if item[2]:
                        p(f"    {item[0]} = {item[1]} # {item[2]}")
                    else:
                        p(f"    {item[0]} = {item[1]}")
            p('')
        elif isinstance(info, StructInfo):
            p(f'{info.name} = Tuple[', end='')
            for i, member in enumerate(info.members):
                if isinstance(member, Comment):
                    continue
                typename = convert_type(member[1])
                if i != 0:
                    p(f', {typename}', end='')
                else:
                    p(f'{typename}', end='')
            p('] # type: ignore')
        elif isinstance(info, UnionInfo):
            p(f'{info.name} = Union[', end='')
            for i, variant in enumerate(info.variants):
                if isinstance(variant, Comment):
                    continue
                typename = convert_type(variant[0])
                if i != 0:
                    p(f', {typename}', end='')
                else:
                    p(f'{typename}', end='')
            p('] # type: ignore')
            p('')
    fp.flush()
    fp.close()

def make_ts(infos:List[Info]) -> None:
    fp = open('messages.ts', 'w', encoding='utf-8')
    def p(*args, **kwargs):
        print(*args, **kwargs, file=fp)
    p('// Generated via', os.path.relpath(__file__))
    p(f'// Input at "{INPUT}"')
    p('// DO NOT EDIT THIS FILE DIRECTLY')
    TsTypes = {
            'int': 'number',
            'float': 'number',
            'double': 'number',
            'str': 'string',
            'bool': 'boolean',
            }
    def convert_type(t:str) -> str:
        if t in TsTypes:
            return TsTypes[t]
        if t.startswith('['):
            inner = t[1:-1]
            inner = convert_type(inner.strip())
            return f'Array<{inner}>'
        return t

    for info in infos:
        if isinstance(info, EnumInfo):
            p(f'const enum {info.name}', '{')
            for item in info.items:
                if isinstance(item, str):
                    p(f'    // {item}')
                elif info.type == 'str':
                    if item[2]:
                        p(f"    {item[0]} = '{item[1]}', // {item[2]}")
                    else:
                        p(f"    {item[0]} = '{item[1]}',")
                else:
                    if item[2]:
                        p(f"    {item[0]} = {item[1]}, // {item[2]}")
                    else:
                        p(f"    {item[0]} = {item[1]},")
            p('}')
            p('')
        elif isinstance(info, StructInfo):
            p(f'type {info.name} = [', end='')
            for i, member in enumerate(info.members):
                if isinstance(member, Comment):
                    continue
                typename = convert_type(member[1])
                if i != 0:
                    p(f', {typename}', end='')
                else:
                    p(f'{typename}', end='')
            p('];')
        elif isinstance(info, UnionInfo):
            p(f'type {info.name} = ', end='')
            for i, variant in enumerate(info.variants):
                if isinstance(variant, Comment):
                    continue
                typename = convert_type(variant[0])
                if i != 0:
                    p(f' | {typename}', end='')
                else:
                    p(f'{typename}', end='')
            p(';')
            p('')
    fp.flush()
    fp.close();


if __name__ == '__main__':
    infos = get_values()
    make_python(infos)
    make_ts(infos)

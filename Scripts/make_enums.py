import os
from typing import List, Tuple, Union, Optional, Set
INPUT = 'message-enum.txt'
class EnumInfo:
    def __init__(self, name:str, type:str):
        assert type in {'str', 'int'}
        self.name = name
        self.type = type
        self.items: List[Union[str, Tuple[str, str, Optional[str]]]] = []
        self.values:Set[str] = set()
        self.keys:Set[str] = set()
    def add_comment(self, comment:str) -> None:
        self.items.append(comment.strip())
    def append(self, k:str, v:str) -> None:
        k = k.strip()
        v = v.strip()
        comment = None
        if '#' in v:
            v, comment = v.split('#')
            v = v.strip()
            comment = comment.strip()
        if k in self.keys:
            raise Exception(self.name, 'duplicate key:', k)
        if v in self.values:
            raise Exception(self.name, 'duplicate value:', v)
        self.keys.add(k)
        self.values.add(v)
        self.items.append((k, v, comment))

def get_values() -> List[EnumInfo]:
    fp = open(INPUT, encoding='utf-8')
    result = []
    current_info: EnumInfo
    for line in fp:
        line = line.rstrip()
        if not line:
            continue
        if line[0] == '\t':
            raise Exception('tab')
        if line.strip()[0] == '#':
            current_info.add_comment(line.strip()[1:])
            continue
        if line[0] != ' ':
            name, type = line.split(':')
            current_info = EnumInfo(name.strip(), type.strip())
            result.append(current_info)
            continue
        k, v = line.split('=')
        current_info.append(k, v)
    fp.close()
    return result

def make_python(infos: List[EnumInfo]) -> None:
    fp = open('WebDnD/messages.py', 'w', encoding='utf-8')
    def p(*args, **kwargs):
        print(*args, **kwargs, file=fp)
    p('# Generated via', os.path.relpath(__file__))
    p(f'# Input at "{INPUT}"')
    p('# DO NOT EDIT THIS FILE DIRECTLY')
    p('from enum import Enum')
    p('')
    for info in infos:
        p(f'class {info.name}({info.type}, Enum):')
        for item in info.items:
            if isinstance(item, str):
                p(f'    # {item}')
                continue
            elif info.type == 'str':
                if item[2]:
                    p(f"    {item[0]} = '{item[1]}' # {item[2]}")
                else:
                    p(f"    {item[0]} = '{item[1]}'")
            else:
                if item[2]:
                    p(f"    {item[0]} = {item[1]} # {item[2]}")
                else:
                    p(f"    {item[0]} = {item[1]}")
        p('')
    fp.flush()
    fp.close()

def make_ts(infos:List[EnumInfo]) -> None:
    fp = open('messages.ts', 'w', encoding='utf-8')
    def p(*args, **kwargs):
        print(*args, **kwargs, file=fp)
    p('// Generated via', os.path.relpath(__file__))
    p(f'// Input at "{INPUT}"')
    p('// DO NOT EDIT THIS FILE DIRECTLY')
    for info in infos:
        p(f'const enum {info.name}', '{')
        for item in info.items:
            if isinstance(item, str):
                p(f'    // {item}')
            elif info.type == 'str':
                if item[2]:
                    p(f"    {item[0]} = '{item[1]}', // {item[2]}")
                else:
                    p(f"    {item[0]} = '{item[1]}',")
            else:
                if item[2]:
                    p(f"    {item[0]} = {item[1]}, // {item[2]}")
                else:
                    p(f"    {item[0]} = {item[1]},")
        p('}')
        p('')
    fp.flush()
    fp.close();


if __name__ == '__main__':
    infos = get_values()
    make_python(infos)
    make_ts(infos)

class ByIdGenerator(html.parser.HTMLParser):
    def __init__(self, filename, fp, *args, **kwargs)->None:
        super().__init__(*args, **kwargs)
        self.fp = fp
        p = self.p
        p('// NOTE: this file was generated by', os.path.relpath(__file__))
        p('// Do NOT edit this file. Your edits will be lost!')
        p('// It was generated by parsing', filename)
        p()
        p('interface NodeIdMap {')

    def p(self, *args):
        print(*args, file=self.fp)
    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if 'id' in attrs:
            typ = TYPES[tag]
            self.p(f"  '{attrs['id']}':", typ+';')

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('infile')
    parser.add_argument('outfile')
    args = parser.parse_args()
    run(**vars(args))

def run(infile: str, outfile:str) -> None:
    with textopen(infile) as fp:
        text = fp.read()

    with textopen(outfile, 'w') as fp:
        g = ByIdGenerator(infile, fp)
        g.feed(text)
        g.p('}')
        g.p()
        g.p('//')
        g.p('// This generated function allows you to get an element by its id,')
        g.p('// in a typed way. This is generated by parsing the output html for tags with ids.')
        g.p('function by_id<K extends keyof NodeIdMap>(id: K): NodeIdMap[K]{')
        g.p('    return document.getElementById(id) as NodeIdMap[K];')
        g.p('}')
    depfile = 'Depends/'+os.path.basename(outfile)+'.dep'
    def m(s:str) -> str:
        try:
            s = os.path.relpath(s) # can throw on windows
        except:
            pass
        return s.replace(' ', r'\ ')
    with textopen(depfile, 'w') as fp:
        fp.write(m(outfile)+': ' + m(infile) + ' ' + m(__file__)+'\n')

if __name__ == '__main__':
    main()
